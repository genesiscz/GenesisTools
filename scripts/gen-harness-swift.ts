#!/usr/bin/env bun
/**
 * Writes the Swift mirror of the harness drivers (plan `.claude/plans/2026-10-30-PlugenizeHarnesses.md`, P7):
 * `src/macos/GenesisKit/Sources/GenesisKitBase/Generated/Harness.swift`, an `enum Harness` with each harness's label,
 * binary, exit command and resume argv, read from the drivers in `src/utils/ai/providers/plugins/<plugin>/harness.ts`.
 * Swift cannot import the TypeScript drivers, so this file is the one copy the apps read, and it is committed so an
 * app builds without bun.
 *
 *   bun scripts/gen-harness-swift.ts           # write the file
 *   bun scripts/gen-harness-swift.ts --check   # exit 1 when the committed file differs from the drivers
 *
 * `src/utils/harness/conformance.test.ts` fails on a stale file too, so a driver change without a regenerated file
 * fails the test suite.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { harnessDrivers, harnessExit, harnessLaunch } from "@genesiscz/utils/ai/providers/harness-index";
import type { HarnessDriver } from "@genesiscz/utils/harness/types";

export const HARNESS_SWIFT_PATH = join(
    import.meta.dirname,
    "..",
    "src/macos/GenesisKit/Sources/GenesisKitBase/Generated/Harness.swift"
);

/** Stands in for the session id while the TypeScript recipe builds the argv; the Swift side passes its parameter. */
const SESSION_PLACEHOLDER = "\u0000session\u0000";

function swiftString(value: string): string {
    return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function swiftArgv(argv: readonly string[]): string {
    return `[${argv.map((token) => (token === SESSION_PLACEHOLDER ? "sessionId" : swiftString(token))).join(", ")}]`;
}

/** One `switch self` over every harness, each case returning the Swift expression `expressionOf` gives. */
function switchOverHarnesses(expressionOf: (driver: HarnessDriver) => string): string[] {
    return [
        "        switch self {",
        ...harnessDrivers().map((driver) => `        case .${driver.id}: return ${expressionOf(driver)}`),
        "        }",
    ];
}

export function renderHarnessSwift(): string {
    return [
        "// Generated by scripts/gen-harness-swift.ts from the TypeScript harness drivers. Do not edit by hand:",
        "// change the driver (src/utils/ai/providers/plugins/<plugin>/harness.ts) and run `bun scripts/gen-harness-swift.ts`.",
        "",
        "/// A coding agent GenesisTools drives, one case per harness driver, in the canonical order.",
        "public enum Harness: String, CaseIterable, Sendable {",
        ...harnessDrivers().map((driver) => `    case ${driver.id}`),
        "",
        '    /// The display name ("Claude Code", "Codex", "Grok").',
        "    public var label: String {",
        ...switchOverHarnesses((driver) => swiftString(driver.identity.label)),
        "    }",
        "",
        "    /// The executable a user starts.",
        "    public var binary: String {",
        ...switchOverHarnesses((driver) => swiftString(driver.identity.binary)),
        "    }",
        "",
        "    /// The slash command that ends an interactive session.",
        "    public var exitCommand: String {",
        ...switchOverHarnesses((driver) => swiftString(harnessExit(driver.id).command)),
        "    }",
        "",
        "    /// Argv that resumes a session in the default home (no pinned account).",
        "    public func resumeArgs(sessionId: String) -> [String] {",
        ...switchOverHarnesses((driver) => swiftArgv(harnessLaunch(driver.id).resumeArgv(SESSION_PLACEHOLDER, {}))),
        "    }",
        "}",
        "",
    ].join("\n");
}

function main(): void {
    const rendered = renderHarnessSwift();

    if (process.argv.includes("--check")) {
        const current = existsSync(HARNESS_SWIFT_PATH) ? readFileSync(HARNESS_SWIFT_PATH, "utf8") : "";

        if (current !== rendered) {
            process.stderr.write(
                `gen-harness-swift: ${HARNESS_SWIFT_PATH} is stale; run bun scripts/gen-harness-swift.ts\n`
            );
            process.exitCode = 1;
            return;
        }

        process.stdout.write("gen-harness-swift: Harness.swift matches the drivers\n");
        return;
    }

    mkdirSync(dirname(HARNESS_SWIFT_PATH), { recursive: true });
    writeFileSync(HARNESS_SWIFT_PATH, rendered);
    process.stdout.write(`gen-harness-swift: wrote ${HARNESS_SWIFT_PATH}\n`);
}

if (import.meta.main) {
    main();
}
