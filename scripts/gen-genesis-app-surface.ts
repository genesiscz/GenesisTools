#!/usr/bin/env bun
/**
 * Writes `src/utils/genesis-tools/capability/generated/app-surface.ts`: the closed unions the actions engine types its
 * needs with. `AppRpcMethod` comes from the Swift `let rpcMethods` list (the source of truth of what `--rpc` answers),
 * `AppPartId` and `AppFaceFlag` from the part table in `src/macos/lib/permissions/parts.ts`. `src/utils` cannot
 * import the macos tool, so this committed file is the one copy it reads.
 *
 *   bun scripts/gen-genesis-app-surface.ts           # write the file
 *   bun scripts/gen-genesis-app-surface.ts --check   # exit 1 when the committed file differs from the sources
 */
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import {
    parseSwiftRpcMethods,
    RPC_METHODS_SWIFT_FILE,
} from "@genesiscz/utils/genesis-tools/capability/app-surface-source";
import { APP_PARTS, type AppPart, HOST_FACES, HOST_WINDOW_FACE } from "../src/macos/lib/permissions/parts";
import { writeOrCheckGenerated } from "./gen-harness-swift";

const ROOT = resolve(import.meta.dirname, "..");
export const APP_SURFACE_PATH = join(ROOT, "src/utils/genesis-tools/capability/generated/app-surface.ts");
const APP_PACKAGE_DIR = join(ROOT, "src/macos/GenesisTools");

export interface AppSurfaceInput {
    rpcMethods: readonly string[];
    parts: readonly Pick<AppPart, "id" | "faces">[];
    hostFace: { flag: string; window: boolean };
    hostFaces?: readonly { flag: string; window: boolean }[];
}

function literal(value: string): string {
    return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

/** `export const <name> = [...] as const;` the way biome prints it: on one line when it fits in 120 columns. */
function constList(name: string, values: readonly string[]): string {
    const inline = `export const ${name} = [${values.map(literal).join(", ")}] as const;`;

    if (inline.length <= 120) {
        return inline;
    }

    return [`export const ${name} = [`, ...values.map((value) => `    ${literal(value)},`), "] as const;"].join("\n");
}

export function renderAppSurface(input: AppSurfaceInput): string {
    const faces = [
        ...input.parts.flatMap((part) =>
            part.faces.map((face) => ({ flag: face.flag, part: part.id, window: face.window }))
        ),
        ...(input.hostFaces ?? [input.hostFace]).map((face) => ({ flag: face.flag, part: null, window: face.window })),
    ];
    const faceRows = faces.map(
        (face) =>
            `    ${literal(face.flag)}: { part: ${face.part === null ? "null" : literal(face.part)}, window: ${face.window} },`
    );

    return [
        "// Generated by scripts/gen-genesis-app-surface.ts. Do not edit; run `bun scripts/gen-genesis-app-surface.ts`.",
        "",
        `/** The methods \`GenesisTools --rpc\` answers (Swift \`let rpcMethods\` in ${RPC_METHODS_SWIFT_FILE}). */`,
        constList("APP_RPC_METHODS", input.rpcMethods),
        "export type AppRpcMethod = (typeof APP_RPC_METHODS)[number];",
        "",
        "/** The optional parts of the app (src/macos/lib/permissions/parts.ts). */",
        constList(
            "APP_PART_IDS",
            input.parts.map((part) => part.id)
        ),
        "export type AppPartId = (typeof APP_PART_IDS)[number];",
        "",
        "/** Every face flag `open -n GenesisTools.app --args <flag>` takes, with the part that ships it (null: the host). */",
        "export const APP_FACES = {",
        ...faceRows,
        "} as const satisfies Record<string, { part: AppPartId | null; window: boolean }>;",
        "export type AppFaceFlag = keyof typeof APP_FACES;",
        "",
    ].join("\n");
}

export function readAppSurfaceInput(): AppSurfaceInput {
    const swift = readFileSync(join(APP_PACKAGE_DIR, RPC_METHODS_SWIFT_FILE), "utf8");
    return {
        rpcMethods: parseSwiftRpcMethods(swift),
        parts: APP_PARTS,
        hostFace: HOST_WINDOW_FACE,
        hostFaces: HOST_FACES,
    };
}

if (import.meta.main) {
    writeOrCheckGenerated({
        tool: "gen-genesis-app-surface",
        path: APP_SURFACE_PATH,
        rendered: renderAppSurface(readAppSurfaceInput()),
    });
}
