#!/usr/bin/env bun
/**
 * Writes the web mirror of the harness drivers: `src/dev-dashboard/ui/src/lib/harness-meta.generated.ts`, one entry
 * per harness with its id, provider plugin, label, badge letter and colour, read from the drivers in
 * `src/utils/ai/providers/plugins/<plugin>/harness.ts`. The dashboard's browser bundle cannot load the drivers, so this
 * file is the one copy it reads (`provider-meta.ts`), the way `gen-harness-swift.ts` writes `Harness.swift` for the
 * apps. The colour is the same `identity.mark.color` the apps draw.
 *
 *   bun scripts/gen-harness-web.ts           # write the file
 *   bun scripts/gen-harness-web.ts --check   # exit 1 when the committed file differs from the drivers
 *
 * `src/utils/harness/conformance.test.ts` fails on a stale file too.
 */

import { join } from "node:path";
import { harnessDrivers } from "@genesiscz/utils/ai/providers/harness-index";
import type { HarnessColor } from "@genesiscz/utils/harness/types";
import { SafeJSON } from "@genesiscz/utils/json";
import { writeOrCheckGenerated } from "./gen-harness-swift";

export const HARNESS_WEB_PATH = join(
    import.meta.dirname,
    "..",
    "src/dev-dashboard/ui/src/lib/harness-meta.generated.ts"
);

/** `#rrggbb` for an sRGB colour with each channel 0 to 1. */
export function hexColor(color: HarnessColor): string {
    const channel = (value: number) =>
        Math.round(value * 255)
            .toString(16)
            .padStart(2, "0");
    return `#${channel(color.red)}${channel(color.green)}${channel(color.blue)}`;
}

export function renderHarnessWeb(): string {
    const entries = harnessDrivers().map((driver) => {
        const fields = {
            id: driver.id,
            plugin: driver.identity.plugin,
            label: driver.identity.label,
            letter: driver.identity.mark.letter,
            color: hexColor(driver.identity.mark.color),
        };
        const body = Object.entries(fields)
            .map(([key, value]) => `${key}: ${SafeJSON.stringify(value)}`)
            .join(", ");
        return `    { ${body} },`;
    });

    return [
        "// Generated by scripts/gen-harness-web.ts from the TypeScript harness drivers. Do not edit by hand:",
        "// change the driver (src/utils/ai/providers/plugins/<plugin>/harness.ts) and run `bun scripts/gen-harness-web.ts`.",
        "",
        "/** A coding agent GenesisTools drives, one entry per harness driver, in the canonical order. */",
        "export interface HarnessMeta {",
        "    /** The harness id (`claude`, `codex`, `grok`). */",
        "    readonly id: string;",
        "    /** The provider plugin that carries the driver (`anthropic-sub`). */",
        "    readonly plugin: string;",
        '    /** The display name ("Claude Code"). */',
        "    readonly label: string;",
        "    /** The letter of the harness's badge. */",
        "    readonly letter: string;",
        "    /** The harness's one colour, the same `identity.mark.color` the apps draw (`#rrggbb`). */",
        "    readonly color: string;",
        "}",
        "",
        "export const HARNESS_META: readonly HarnessMeta[] = [",
        ...entries,
        "];",
        "",
    ].join("\n");
}

if (import.meta.main) {
    writeOrCheckGenerated({ tool: "gen-harness-web", path: HARNESS_WEB_PATH, rendered: renderHarnessWeb() });
}
