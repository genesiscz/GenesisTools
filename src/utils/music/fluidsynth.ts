export function fluidSynthArgs(options: { soundfont: string; midi: string; raw: string }): string[] {
    return [
        "-n",
        "-i",
        "-q",
        "-F",
        options.raw,
        "-T",
        "wav",
        "-O",
        "float",
        "-r",
        "48000",
        "-g",
        "0.5",
        "-R",
        "0",
        "-C",
        "0",
        "-o",
        "synth.cpu-cores=1",
        "-o",
        "synth.midi-bank-select=xg",
        "-o",
        "player.timing-source=sample",
        options.soundfont,
        options.midi,
    ];
}
