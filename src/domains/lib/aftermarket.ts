export function parkingServiceFor(nameservers: string[]): string | undefined {
    for (const ns of nameservers) {
        const host = ns.toLowerCase().replace(/\.$/, "");
        for (const [suffix, service] of Object.entries(PARKING_NAMESERVERS)) {
            if (host === suffix || host.endsWith(`.${suffix}`)) {
                return service;
            }
        }
    }

    return undefined;
}

/** Marketplace hosts, matched against the final URL only: a page that merely links to one is not for sale. */
const URL_MARKERS: [RegExp, string][] = [
    [/sedoparking\.com|sedo\.com\/search\/details/i, "Sedo"],
    [/afternic\.com/i, "Afternic"],
    [/dan\.com\/buy-domain/i, "Dan.com"],
    [/hugedomains\.com/i, "HugeDomains"],
    [/atom\.com\/name\/|squadhelp\.com/i, "Atom"],
    [/undeveloped\.com/i, "Undeveloped"],
    [/bodis\.com/i, "Bodis"],
    [/parkingcrew/i, "ParkingCrew"],
    [/buydomains\.com/i, "BuyDomains"],
    [/brandbucket\.com/i, "BrandBucket"],
    [/domainmarket\.com/i, "DomainMarket"],
    [/efty\.com/i, "Efty"],
    [/sav\.com\/(domains|marketplace)/i, "Sav"],
];

/** Markers only a parking page itself carries, so they may match the page body. */
const PAGE_MARKERS: [RegExp, string][] = [
    [/sedoParkingUrl/, "Sedo"],
    [/this webpage was generated by the domain owner/i, "a parking service"],
];

const MAX_REDIRECTS = 5;

/** GET with redirects followed by hand: every hop must be http(s) and resolve to public addresses only. */
async function fetchLanding(url: string): Promise<HttpResponse<unknown>> {
    let current = url;
    for (let hop = 0; hop <= MAX_REDIRECTS; hop++) {
        const target = new URL(current);
        if (target.protocol !== "https:" && target.protocol !== "http:") {
            throw new Error(`redirect to ${target.protocol} refused`);
        }

        await assertPublicHost(target.hostname);
        const response = await request(current, {
            label: "landing",
            timeoutMs: 10_000,
            redirect: "manual",
            headers: { "user-agent": "Mozilla/5.0 (Macintosh) tools-domains" },
        });
        const location = response.headers.get("location");
        if (response.status < 300 || response.status >= 400 || !location) {
            return { ...response, url: current };
        }

        current = new URL(location, current).toString();
    }

    throw new Error(`more than ${MAX_REDIRECTS} redirects`);
}

const FOR_SALE_TEXT = /(this domain|the domain [\w.-]+) (is|may be) for sale|buy this domain|make an offer/i;

export interface LandingProbe {
    finalUrl?: string;
    httpStatus?: number;
    marketplace?: string;
    /** The page says the name is for sale, without naming a known marketplace (a weak signal). */
    forSaleText: boolean;
    /** Afternic's public listing page; it shows a buy-now price when one is set. */
    afternicUrl: string;
}

/** Second for-sale signal after the nameservers: where the site lands and what the page says. */
export async function probeLanding(domain: string): Promise<LandingProbe> {
    const afternicUrl = `https://www.afternic.com/forsale/${domain}`;
    for (const scheme of ["https", "http"]) {
        try {
            const response = await fetchLanding(`${scheme}://${domain}/`);
            const page = response.text.slice(0, 200_000);
            const marketplace =
                URL_MARKERS.find(([re]) => re.test(response.url))?.[1] ??
                PAGE_MARKERS.find(([re]) => re.test(page))?.[1];
            return {
                finalUrl: response.url,
                httpStatus: response.status,
                marketplace,
                forSaleText: FOR_SALE_TEXT.test(response.text),
                afternicUrl,
            };
        } catch (error) {
            logger.debug({ domain, scheme, error }, "domains: landing probe failed");
        }
    }

    return { forSaleText: false, afternicUrl };
}

export interface WaybackSummary {
    first?: string;
    last?: string;
}

function cdxDate(rows: string[][] | null): string | undefined {
    const value = rows?.[1]?.[0];
    return value ? `${value.slice(0, 4)}-${value.slice(4, 6)}-${value.slice(6, 8)}` : undefined;
}

/** First and last Wayback Machine capture (CDX API, no auth). Dates are YYYY-MM-DD. */
export async function waybackSummary(domain: string): Promise<WaybackSummary> {
    const base = `https://web.archive.org/cdx/search/cdx?url=${encodeURIComponent(domain)}&output=json&fl=timestamp`;
    const [first, last] = await Promise.all([
        request<string[][]>(`${base}&limit=1`, { label: "wayback first", timeoutMs: 20_000 }),
        request<string[][]>(`${base}&limit=-1`, { label: "wayback last", timeoutMs: 20_000 }),
    ]);
    return { first: cdxDate(first.body), last: cdxDate(last.body) };
}

interface CrtShEntry {
    not_before: string;
    not_after: string;
    issuer_name: string;
}

export interface CertificateSummary {
    count: number;
    first?: string;
    last?: string;
}

/** TLS certificates ever logged for the name (crt.sh, no auth): proof a site really ran there. */
export async function certificateSummary(domain: string): Promise<CertificateSummary> {
    const response = await request<CrtShEntry[]>(`https://crt.sh/?q=${encodeURIComponent(domain)}&output=json`, {
        label: "crt.sh",
        timeoutMs: 25_000,
    });
    const entries = Array.isArray(response.body) ? response.body : [];
    const dates = entries.map((entry) => entry.not_before.slice(0, 10)).sort();
    return { count: entries.length, first: dates[0], last: dates.at(-1) };
}
